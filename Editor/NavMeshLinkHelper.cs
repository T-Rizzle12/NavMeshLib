using System;
using System.Collections.Generic;
using System.Text;
using Unity.AI.Navigation;
using UnityEngine;
using UnityEngine.AI;

namespace NavMeshLib.Editor
{
    /// <summary>
    /// A helper mono behavior made to allow moon makers to use <see cref="NavMeshLink"/>'s with transform's representing
    /// the start and end position like <see cref="OffMeshLink"/>s
    /// </summary>
    [RequireComponent(typeof(NavMeshLink))]
    public class NavMeshLinkHelper : MonoBehaviour
    {
        // Public
        /// <summary>
        /// The NavMeshLink to manage.
        /// </summary>
        [Tooltip("The NavMeshLink to manage.")]
        public NavMeshLink? link = null!;

        /// <summary>
        /// The start transform of this NavMeshLink.
        /// </summary>
        [Tooltip("The start transform of this NavMeshLink.")]
        public Transform? startTransform = null;

        /// <summary>
        /// The end transform of this NavMeshLink.
        /// </summary>
        [Tooltip("The end transform of this NavMeshLink.")]
        public Transform? endTransform = null;

        /// <summary>
        /// How often should we check if the NavMeshLink has moved. (In Seconds)
        /// </summary>
        [Tooltip("How often should we check if the NavMeshLink has moved. (In Seconds)")]
        public float updateInterval = 0.5f;

        /// <summary>
        /// What is the maximum range when searching for the nearest NavArea to the <see cref="startTransform"/> and <see cref="endTransform"/>.
        /// </summary>
        [Tooltip("What is the maximum range when searching for the nearest NavArea to the startTransform and endTransform.")]
        public float nearbyAreaRange = 2f;

        /// <summary>
        /// Was this automatically generated by NavMeshLib?
        /// </summary>
        [SerializeField]
        [HideInInspector]
        public bool GeneratedByNavMeshLib { get; internal set; } = false;

        // Internal
        /// <summary>
        /// Some animations change <see cref="OffMeshLink.activated"/>. Since I can't edit those at runtime,
        /// my plan is to check the state and enable and disable our attached link as needed!
        /// </summary>
        [SerializeField]
        [HideInInspector]
        internal OffMeshLink? OffMeshToMimic = null;

        // Private
        private float updateTimer = 0f;

        private bool? lastMimicActivated = null;

        private bool isDestroyed = false;

        private void Start()
        {
            updateTimer = 0f;
            SyncPoints();

            // Force autoupdate on
            if (link != null)
            {
                link.autoUpdate = true;
            }
        }

        private void Update()
        {
            // We are marked for destruction, do nothing
            if (isDestroyed) return;

            // Update our active status
            SyncActivatedState();

            // Update our internal timer
            updateTimer += Time.deltaTime;
            if (updateTimer > updateInterval)
            {
                updateTimer = 0f;
                SyncPoints();
            }
        }

        /// <summary>
        /// Syncs our <see cref="link"/>'s start and end points with the ones set on the object
        /// </summary>
        public void SyncPoints()
        {
            // We are marked for destruction, do nothing
            if (isDestroyed) return;

            RoundManager instanceRM = RoundManager.Instance;
            if (instanceRM != null
                && link != null 
                && startTransform != null 
                && endTransform != null)
            {
                // Find the closest NavArea to our given transforms
                NavMeshQueryFilter queryFilter = new NavMeshQueryFilter { agentTypeID = link.agentTypeID, areaMask = NavMesh.AllAreas };
                Vector3 startPos = instanceRM.GetNavMeshPosition(startTransform.position, queryFilter, instanceRM.navHit, nearbyAreaRange);
                Vector3 endPos = instanceRM.GetNavMeshPosition(endTransform.position, queryFilter, instanceRM.navHit, nearbyAreaRange);

                // Update our link
                link.startPoint = WorldToLinkPoint(link, startPos);
                link.endPoint = WorldToLinkPoint(link, endPos);
            }
        }

        /// <summary>
        /// Copies our activated state with the <see cref="OffMeshLink"/> we are mimicing. <br/>
        /// Does nothing if <see cref="OffMeshToMimic"/> is null
        /// </summary>
        public void SyncActivatedState()
        {
            // No link or we are not mimicing an OffMeshLink
            if (isDestroyed
                || link == null 
                || OffMeshToMimic == null)
            {
                return;
            }

            bool activated = OffMeshToMimic.enabled && OffMeshToMimic.activated;
            if (lastMimicActivated.HasValue &&
                lastMimicActivated.Value == activated)
            {
                return;
            }

            lastMimicActivated = activated;
            link.enabled = activated;
        }

        private void OnDestroy()
        {
            isDestroyed = true;
            if (link != null)
            {
                UnityEngine.Object.Destroy(link); // Destroy the link we are supposed to be managing
            }
        }

        internal static Vector3 WorldToLinkPoint(NavMeshLink link, Vector3 worldPosition)
        {
            return Quaternion.Inverse(link.transform.rotation) * (worldPosition - link.transform.position);
        }
    }
}
